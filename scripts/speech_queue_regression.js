'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const revoked = [], starts = [], players = [], pendingSynth = [], pendingPlay = [];
const box = {Promise, AbortController, URL:{revokeObjectURL:u=>revoked.push(u)}};
box.window = box;
vm.runInNewContext(fs.readFileSync(process.env.RYZA_TURN_SOURCE || path.join(__dirname,'../web/js/turn.js'),'utf8'),box);
const T = box.Turn;
const tick = async () => { for(let i=0;i<8;i++) await Promise.resolve(); };
(async()=>{
 assert.deepEqual(Array.from(T.splitSentences('欢迎回来！今天想一起去冒险吗？我准备好了。')), ['欢迎回来！今天想一起去冒险吗？','我准备好了。']);
 assert.deepEqual(Array.from(T.splitSentences('今日は一緒に冒険しよう。材料も持ってきたよ！')),['今日は一緒に冒険しよう。','材料も持ってきたよ！']);
 assert.deepEqual(Array.from(T.splitSentences('Value is 3.14. A second sentence.')),['Value is 3.14.','A second sentence.']);
 T.setSynth((text,meta,signal)=>{starts.push(text);return new Promise(resolve=>pendingSynth.push({resolve,signal,meta}));});
 T.setPlayer((url,signal)=>{players.push(url);return new Promise(resolve=>{pendingPlay.push(resolve);signal.addEventListener('abort',resolve,{once:true});});});
 T.speak('first',{prefetch:true,translated:true}); T.speak('second',{prefetch:true}); T.speak('third',{prefetch:true});
 assert.deepEqual(starts,['first']);
 assert.equal(pendingSynth[0].meta.translated,true,'preview line lost its target-language marker');
 pendingSynth[0].resolve('blob:first'); await tick();
 assert.deepEqual(players,['blob:first']); assert.deepEqual(starts,['first','second']);
 pendingSynth[1].resolve('blob:second'); await tick();
 assert.deepEqual(players,['blob:first']);
 pendingPlay[0](); await tick();
 assert.deepEqual(players,['blob:first','blob:second']);
 assert.deepEqual(starts,['first','second','third']);
 T.stopAll('test-cancel'); assert.equal(pendingSynth[2].signal.aborted,true);
 pendingSynth[2].resolve('blob:third'); await tick();
 assert(revoked.includes('blob:third')); assert(!players.includes('blob:third'));
 assert.equal(T.state(),'idle'); assert.equal(T.waiting(),0);
 T.speak('new turn',{prefetch:true}); pendingSynth[3].resolve('blob:new'); await tick();
 assert.equal(players.at(-1),'blob:new'); pendingPlay.at(-1)(); await tick();
 assert.equal(T.state(),'idle');
 console.log('SPEECH QUEUE: PASS (Chinese/Japanese/decimal boundaries, ordered playback, one ahead, cancellation, next turn)');
})().catch(e=>{console.error(e);process.exitCode=1;});
